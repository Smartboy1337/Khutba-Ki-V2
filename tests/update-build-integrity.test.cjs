const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const pkg = require(path.join(root,'package.json'));
const lock = require(path.join(root,'package-lock.json'));
assert.equal(pkg.version, '1.1.11');
assert.equal(lock.version, pkg.version);
assert.equal(lock.packages[''].version, pkg.version);
const main = fs.readFileSync(path.join(root,'src/main/khutbahAutoUpdater.ts'),'utf8');
assert.match(main,/autoDownload\s*=\s*true/);
assert.match(main,/autoInstallOnAppQuit\s*=\s*true/);
assert.match(main,/15 \* 60 \* 1000/);
assert.match(main,/update-downloaded/);
assert.match(main,/scheduleRetry/);
const ui = fs.readFileSync(path.join(root,'src/renderer/src/ui/App.tsx'),'utf8');
assert.match(ui,/UPDATE-SYSTEM AKTIV/);
assert.match(ui,/TEST-BUILD 1\.1\.11/);
assert.match(ui,/checkUpdatesNow/);
assert.match(ui,/updateStatus\?\.message/);
console.log('Prüfung OK: v1.1.11, automatische Downloads, Status-Anzeige, Retry und Versionen.');
